// Files without an informative extension.
const NAME_TO_LANG = {
  ".bash_profile": "shell",
  ".bashrc": "shell",
  ".editorconfig": "ini",
  ".profile": "shell",
  ".vimrc": "plaintext",
  ".zshrc": "shell",
  containerfile: "dockerfile",
  dockerfile: "dockerfile",
  gemfile: "ruby",
  "gemfile.lock": "plaintext",
  gnumakefile: "plaintext",
  jenkinsfile: "plaintext",
  makefile: "plaintext",
  rakefile: "ruby",
  vagrantfile: "ruby",
};

export function languageOf(path) {
  const base = String(path || "").split(/[\\/]/).pop().toLowerCase();
  const named = NAME_TO_LANG[base];
  if (named) return named;

  // dotfiles like `.env`, `.env.local` are key=value config
  if (base === ".env" || base.startsWith(".env.")) return "ini";

  const dot = base.lastIndexOf(".");
  const ext = dot >= 0 ? base.slice(dot + 1) : "";
  return EXT_TO_LANG[ext] || "plaintext";
}
